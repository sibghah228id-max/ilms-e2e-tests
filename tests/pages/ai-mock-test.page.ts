import { type Page, type Locator, expect } from '@playwright/test';

/** Where the assessment got to: how many questions it asked, and what the insights screen said. */
export type MockTestOutcome = {
  /** Questions answered, which is also what the counter said the test held. */
  questions: number;
  /** "Question N of M" as the first question reported it. */
  total: number;
  /** Whether the analysing state was caught before the insights replaced it. */
  analysed: boolean;
};

/**
 * The "AI Mock Test" sheet, opened from the "AI Resources" popup on an applied job's page.
 *
 * Read off the staging portal on 2026-10-27, where the flow runs entirely inside one dialog:
 *
 *   card click -> "Preparing your mock test"      the questions are generated server-side (~1 min,
 *                                                 and already-generated tests skip straight past)
 *             -> "Start the Assessment"           an intro screen: "5 multiple-choice questions"
 *             -> "Question N of M"                one MCQ at a time, 4 options, "Previous"/"Next"
 *             -> the last question's finish       -> the analysing state -> "Detailed AI Insights"
 *
 * Two things shape how this is driven. The whole test runs against a countdown (5 minutes for 5
 * questions, shown as "4:58" in the header), so nothing here waits around between questions: each
 * step keys off the counter or a button's enabled state rather than a sleep. And "Next" is disabled
 * until the current question has an answer, which is the portal's own guard against advancing
 * unanswered - this presses it only once it is enabled, so it can never skip a question.
 */
export class AiMockTestSheet {
  /** The dialog the whole flow happens in. */
  readonly sheet: Locator;
  readonly heading: Locator;
  readonly preparing: Locator;
  readonly startAssessment: Locator;
  /** "Question 2 of 5"; styled uppercase, so matched without case. */
  readonly questionCounter: Locator;
  readonly questionText: Locator;
  readonly options: Locator;
  readonly previousButton: Locator;

  constructor(private readonly page: Page) {
    this.sheet = page.getByRole('dialog').last();
    this.heading = this.sheet.getByRole('heading', { level: 1, name: 'AI Mock Test' });
    this.preparing = this.sheet.getByRole('heading', { name: /preparing your mock test/i });
    this.startAssessment = this.sheet.getByRole('button', { name: /start the assessment/i });
    this.questionCounter = this.sheet.getByText(/question\s+\d+\s+of\s+\d+/i);
    this.questionText = this.sheet.getByRole('heading', { level: 3 });
    // Each option is a <label> wrapping a hidden radio, inside the question's own radiogroup.
    this.options = this.sheet.locator('[role="radiogroup"] label');
    this.previousButton = this.sheet.getByRole('button', { name: /^previous$/i });
  }

  /**
   * The button that moves the assessment on. The last question swaps "Next" for a finishing
   * action, and the wording of that is taken as it comes rather than pinned to one label.
   */
  get advanceButton(): Locator {
    return this.sheet.getByRole('button', { name: /^(next|finish|submit|see results|view results|complete)/i });
  }

  /** The analysing state between the last answer and the insights. */
  get analysing(): Locator {
    return this.sheet.getByText(/analys|analyz/i);
  }

  /** The results screen the analysis ends on. */
  get insights(): Locator {
    return this.sheet.getByText(/detailed ai insights/i);
  }

  /**
   * Waits out the server-side question generation and stops on the intro screen.
   *
   * A test generated by an earlier run is served straight away, so the preparing state may never
   * be seen at all - which is why this waits for the intro rather than for preparing to appear.
   */
  async waitUntilPrepared(timeout = 4 * 60_000) {
    await expect(this.heading, 'the AI Mock Test sheet should open').toBeVisible({ timeout: 30_000 });
    await expect(this.preparing, 'the questions should finish being prepared').toHaveCount(0, { timeout });
    await expect(this.startAssessment, 'the prepared test should offer "Start the Assessment"').toBeVisible({
      timeout: 60_000,
    });
  }

  /** "Start the Assessment", through to the first question. */
  async beginAssessment() {
    await this.startAssessment.click();
    await expect(this.questionCounter.first(), 'the assessment should open on its first question').toBeVisible({
      timeout: 60_000,
    });
  }

  /** The counter, as { current, total }. */
  async position(): Promise<{ current: number; total: number }> {
    const text = (await this.questionCounter.first().innerText()).replace(/\s+/g, ' ').trim();
    const match = text.match(/question\s+(\d+)\s+of\s+(\d+)/i);
    expect(match, `the question counter read "${text}"`).not.toBeNull();
    return { current: Number(match![1]), total: Number(match![2]) };
  }

  /**
   * Answers the question on screen by taking its first option, and returns the option's text.
   *
   * A mock test is not being scored for correctness here - what is under test is that the portal
   * takes an answer and lets the assessment move on - so the first option is as good as any, and
   * picking it the same way every time keeps a failed run reproducible.
   */
  async answerCurrent(): Promise<string> {
    // Staging only serves single-choice MCQs, but a multi-select or free-text question is answered
    // too rather than left blank: whichever input the question renders is the one that gets used.
    const checkboxes = this.sheet.locator('label').filter({ has: this.page.locator('input[type="checkbox"]') });
    const textbox = this.sheet.locator('textarea, input[type="text"], input:not([type])').locator('visible=true');
    await expect(
      this.options.or(checkboxes).or(textbox).first(),
      'the question should offer a way to answer it',
    ).toBeVisible({ timeout: 30_000 });

    let answer: string;
    if (await this.options.count()) {
      const count = await this.options.count();
      expect(count, 'a multiple-choice question should offer more than one option').toBeGreaterThan(1);
      const option = this.options.first();
      answer = (await option.innerText()).replace(/\s+/g, ' ').trim();
      await option.click();
    } else if (await checkboxes.count()) {
      const option = checkboxes.first();
      answer = (await option.innerText()).replace(/\s+/g, ' ').trim();
      await option.click();
    } else {
      answer = 'Automated answer: I would break the problem down, test each part and verify the result.';
      await textbox.first().fill(answer);
    }

    // The portal keeps "Next" disabled until the question has an answer, so this is the check that
    // the click registered - and the reason the run can never advance an unanswered question.
    await expect(
      this.advanceButton.last(),
      `answering "${answer}" should enable the button that moves the assessment on`,
    ).toBeEnabled({ timeout: 30_000 });

    return answer;
  }

  /**
   * Answers every question and finishes the test, returning what it came to.
   *
   * The number of questions is read from the counter rather than assumed, and the loop follows the
   * counter forward, so a test of any length is handled. The finishing press happens exactly once:
   * the loop leaves as soon as the last question has been sent.
   */
  async completeAssessment(): Promise<MockTestOutcome> {
    const { total } = await this.position();
    expect(total, 'the assessment should hold at least one question').toBeGreaterThan(0);

    let answered = 0;
    for (let n = 1; n <= total; n++) {
      const at = await this.position();
      expect(at.current, `the assessment should be on question ${n}`).toBe(n);

      await this.answerCurrent();
      answered++;

      const advance = this.advanceButton.last();
      await expect(advance).toBeEnabled({ timeout: 30_000 });
      await advance.click();

      // Not the last one: the counter has to move on before the next answer is given, otherwise the
      // same question would be answered twice.
      if (n < total) {
        await expect(this.questionCounter.first(), `the assessment should move to question ${n + 1}`).toHaveText(
          new RegExp(`question\\s+${n + 1}\\s+of\\s+${total}`, 'i'),
          { timeout: 60_000 },
        );
      }
    }

    // ---- Submitted once, and now being analysed: the portal has to say so before the insights.
    await expect(this.analysing.first(), 'the finished assessment should show that it is being analysed').toBeVisible({
      timeout: 30_000,
    });
    const analysed = true;

    await expect(this.insights.first(), 'the analysis should end on "Detailed AI Insights"').toBeVisible({
      timeout: 5 * 60_000,
    });

    return { questions: answered, total, analysed };
  }

  /** Closes the sheet through its header X, leaving the job page underneath usable again. */
  async close() {
    const x = this.sheet.getByRole('button').filter({ hasText: /^$/ });
    if (await x.count()) {
      await x.last().click();
    } else {
      await this.page.keyboard.press('Escape');
    }
    await expect(this.page.getByRole('dialog'), 'the sheet should close').toHaveCount(0, { timeout: 30_000 });
  }
}
